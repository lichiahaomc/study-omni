/** 从 "数学 · 高中" 这样的 value 里拆出学科名与学段 */
function splitSubject(value) {
  const [name, stage] = String(value || '').split('·').map(s => s.trim());
  return { name: name || '', stage: stage || '' };
}

/**
 * 生成 system prompt。
 * 学段或学科未命中时优雅降级,而不是抛错 —— 前端加了新学科不会让服务崩掉。
 */
export function buildSystemPrompt({ subject, style }) {
  const { name, stage } = splitSubject(subject);
  const meta = SUBJECTS[name + ' · ' + stage] || SUBJECTS[name] || null;

  const tone = STAGE_TONE[stage] || STAGE_TONE['高中'];
  const strategy = meta ? KIND_STRATEGY[meta.kind] : KIND_STRATEGY.math;

  const parts = [
    `你是 StudyOmni 的学科答疑助手,正在辅导${stage || '该'}学生的「${name || '当前'}」。`,
    '教学原则:',
    tone,
    strategy,
  ];

  if (meta?.focus) parts.push(`本学科重点:${meta.focus}`);

  // 回答风格来自设置面板
  const STYLES = {
    concise: '篇幅要克制,直接给结论和最短路径,不展开背景。',
    balanced: '结论与展开并重,一个例子足够,不拔高。',
    step: '必须分步骤逐步推导,每一步单独成行,不能跳步。',
    socratic: '不要直接给答案。用反问引导学生自己想到下一步,'
            + '在关键处给出提示;学生卡住时再逐步揭示。',
  };
  parts.push(STYLES[style] || STYLES.balanced);

  parts.push(
    '格式要求:使用 Markdown;数学公式一律用 LaTeX'
    + '(行内 $...$,独立成行 $$...$$);不要编造题目里没有的条件。'
  );

  return parts.join('\n');
}
