function splitSubject(value) {
  const [name, stage] = String(value || '').split('·').map(s => s.trim());
  return { name: name || '', stage: stage || '' };
}

/**
 * 查学科条目,三级降级:
 *   ① "学科 · 学段" 精确命中(正常路径)
 *   ② 只按学科名跨学段找(前端只传了名字、或学段被改过)
 *   ③ 都没有 -> null,由调用方退到通用策略
 * 第 ② 级以前是假的:写成 SUBJECTS[name] 但表里根本没有裸名字的键,
 * 于是"降级"永远命中不了。现在真的按名字前缀找。
 */
function findSubject(name, stage) {
  if (!name) return null;
  const exact = SUBJECTS[name + ' · ' + stage];
  if (exact) return exact;
  if (!stage) {
    const key = Object.keys(SUBJECTS).find(k => k.split('·')[0].trim() === name);
    if (key) return SUBJECTS[key];
  }
  return null;
}

/* 学段对应的"称呼",让开场那句话读起来自然 */
const AUDIENCE = {
  '小学': '小学生', '初中': '初中生', '高中': '高中生', '大学': '大学生',
  '进阶': '有编程 / 技术基础的进阶学习者',
  '通识': '出于兴趣了解通识内容的学习者',
};

/**
 * 生成 system prompt。
 * 学段或学科未命中时优雅降级,而不是抛错 —— 前端加了新学科不会让服务崩掉。
 */
export function buildSystemPrompt({ subject, style }) {
  const { name, stage } = splitSubject(subject);
  const meta = findSubject(name, stage);

  const tone = STAGE_TONE[stage] || STAGE_TONE['高中'];
  const strategy = meta ? KIND_STRATEGY[meta.kind] : KIND_STRATEGY.math;
  const audience = AUDIENCE[stage] || '该';

  const parts = [
    `你是 StudyOmni 的学科答疑助手,正在辅导${audience}的「${name || '当前学科'}」。`,
    '教学原则:',
    tone,
    strategy,
  ];

  if (meta?.focus) parts.push(`本学科重点:${meta.focus}`);

  parts.push(
    '如果用户的问题明显不属于所选学科(比如在"语文"下问了一道编程题),'
    + '就按问题本身所属的学科来回答 —— 上面的学科设定只用于把握讲解风格与深度,'
    + '不要为了贴合所选学科而硬套术语或话术。'
  );

  // 回答风格来自设置面板
  const STYLES = {
    concise: '篇幅要克制,直接给结论和最短路径,不展开背景。',
    balanced: '结论与展开并重,一个例子足够,不拔高。',
    step: '必须分步骤逐步推导,每一步单独成行,不能跳步。',
    socratic: '不要直接给答案。用反问引导学生自己想到下一步,'
            + '在关键处给出提示;学生卡住时再逐步揭示。',
  };
  parts.push(STYLES[style] || STYLES.balanced);

  parts.push(
    '格式要求:使用 Markdown;数学公式一律用 LaTeX'
    + '(行内 $...$,独立成行 $$...$$);代码用围栏代码块并标明语言;'
    + '不要编造题目里没有的条件。'
  );

  return parts.join('\n');
}

